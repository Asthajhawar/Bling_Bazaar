// Helper to get unique categories
export function getCategories(): string[] {
  return [...new Set(products.map((p) => p.category))];
}

// Helper to get products by category
export function getProductsByCategory(category: string): GalleryItem[] {
  return products.filter((p) => p.category === category);
}

// Helper to get subcategories for a given category
export function getSubCategories(category: string): string[] {
  const items = getProductsByCategory(category);
  return [...new Set(items.map((p) => p.subCategory))];
}

// Helper to create a URL-safe slug from category name
export function categoryToSlug(category: string): string {
  return category.toLowerCase().replace(/\s+/g, '-');
}

// Helper to find category from slug
export function slugToCategory(slug: string): string | undefined {
  return getCategories().find(
    (c) => categoryToSlug(c) === slug
  );
}

// Category metadata for display cards on homepage
export interface CategoryMeta {
  name: string;
  slug: string;
  count: number;
  coverImage: string;
  priceRange: string;
}

export function getCategoryMeta(): CategoryMeta[] {
  const categories = getCategories();
  return categories.map((name) => {
    const items = getProductsByCategory(name);
    const prices = items.map((i) => parseInt(i.priceRange.replace(/[₹,]/g, '')));
    const min = Math.min(...prices);
    const max = Math.max(...prices);
    const priceRange = min === max ? `₹${min}` : `₹${min} – ₹${max}`;

    return {
      name,
      slug: categoryToSlug(name),
      count: items.length,
      coverImage: items[0].image,
      priceRange,
    };
  });
}
